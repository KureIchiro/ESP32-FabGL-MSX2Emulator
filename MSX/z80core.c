  case 0xA8: cyc -= 16; { const uint8_t v = RD8(RHL); WR8(RDE, v); RHL -= 1; RDE -= 1; RBC--; const uint8_t n = (uint8_t)(v + RA); RF = (RF & (SF | ZF | CF)) | (RBC ? PF : 0) | (n & XF) | ((n & 0x02) << 4); } break;
  case 0xA9: cyc -= 16; { const uint8_t v = RD8(RHL); const uint8_t r = (uint8_t)(RA - v); const uint8_t h = (RA ^ v ^ r) & HF; RHL -= 1; RBC--; RWZ -= 1; const uint8_t n = (uint8_t)(r - (h >> 4)); RF = (RF & CF) | NF | (sz53[r] & (SF | ZF)) | h | (RBC ? PF : 0) | (n & XF) | ((n & 0x02) << 4); } break;

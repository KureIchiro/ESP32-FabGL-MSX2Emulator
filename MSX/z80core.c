  case 0xB2: cyc -= 16; { const uint8_t v = IN8(RBC); RWZ = (uint16_t)(RBC + 1); WR8(RHL, v); RHL += 1; RB--; const unsigned k = v + (uint8_t)(RC + 1); RF = sz53[RB] | ((v >> 6) & NF) | (k > 255 ? (HF | CF) : 0) | (sz53p[(k & 7) ^ RB] & PF); if (RB) { cyc -= 5; pc = (uint16_t)(pc - 2); } } break;
  case 0xB3: cyc -= 16; { const uint8_t v = RD8(RHL); RB--; RWZ = (uint16_t)(RBC + 1); OUT8(RBC, v); RHL += 1; const unsigned k = v + RL; RF = sz53[RB] | ((v >> 6) & NF) | (k > 255 ? (HF | CF) : 0) | (sz53p[(k & 7) ^ RB] & PF); if (RB) { cyc -= 5; pc = (uint16_t)(pc - 2); } } break;
  case 0xB8: cyc -= 16; { const uint8_t v = RD8(RHL); WR8(RDE, v); RHL -= 1; RDE -= 1; RBC--; const uint8_t n = (uint8_t)(v + RA); RF = (RF & (SF | ZF | CF)) | (RBC ? PF : 0) | (n & XF) | ((n & 0x02) << 4); if (RBC) { cyc -= 5; pc = (uint16_t)(pc - 2); RWZ = (uint16_t)(pc + 1); } } break;
  case 0xB9: cyc -= 16; { const uint8_t v = RD8(RHL); const uint8_t r = (uint8_t)(RA - v); const uint8_t h = (RA ^ v ^ r) & HF; RHL -= 1; RBC--; RWZ -= 1; const uint8_t n = (uint8_t)(r - (h >> 4)); RF = (RF & CF) | NF | (sz53[r] & (SF | ZF)) | h | (RBC ? PF : 0) | (n & XF) | ((n & 0x02) << 4); if (RBC && r) { cyc -= 5; pc = (uint16_t)(pc - 2); RWZ = (uint16_t)(pc + 1); } } break;

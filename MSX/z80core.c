#define SF 0x80
#define ZF 0x40
#define YF 0x20
#define HF 0x10
#define XF 0x08
#define PF 0x04
#define VF 0x04
#define NF 0x02
#define CF 0x01

static uint8_t sz53[256];
static uint8_t sz53p[256];

static void make_tables(void)
{
  for (int i = 0; i < 256; i++) {
    int p = 1;
    for (int b = 0; b < 8; b++) p ^= (i >> b) & 1;
    sz53[i] = (uint8_t)((i & (SF | YF | XF)) | (i ? 0 : ZF));
    sz53p[i] = (uint8_t)(sz53[i] | (p ? PF : 0));
  }
}

